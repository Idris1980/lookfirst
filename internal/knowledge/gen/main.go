// Command gen refreshes what LookFirst knows about Azure and AWS from their
// own published lists: every Azure resource type with its newest API
// version, from Microsoft's template schemas, and every AWS resource type
// with its documentation page, from the CloudFormation resource
// specification. It writes them next to the knowledge package, which
// embeds them, so the reader itself never goes on the internet.
//
//	go run ./internal/knowledge/gen
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	azureSource = "https://raw.githubusercontent.com/Azure/azure-resource-manager-schemas/main/schemas/common/autogeneratedResources.json"
	awsSource   = "https://d1uauaxba7bl26.cloudfront.net/latest/gzip/CloudFormationResourceSpecification.json"
)

var schemaRef = regexp.MustCompile(`/schemas/([0-9]{4}-[0-9]{2}-[0-9]{2}(?:-preview)?)/([A-Za-z0-9.]+)\.json#/resourceDefinitions/([A-Za-z0-9_]+)`)

func main() {
	dir := filepath.Join("internal", "knowledge")
	today := time.Now().UTC().Format("2006-01-02")

	az, err := fetch(azureSource)
	check(err)
	types := map[string]string{} // type -> newest API version
	for _, m := range schemaRef.FindAllStringSubmatch(string(az), -1) {
		t := m[2] + "/" + strings.ReplaceAll(m[3], "_", "/")
		if v, ok := types[t]; !ok || m[1] > v {
			types[t] = m[1]
		}
	}
	if len(types) < 1000 {
		check(fmt.Errorf("only %d Azure types found; the source may have changed", len(types)))
	}
	write(filepath.Join(dir, "azure.json"), map[string]any{"updated": today, "source": azureSource, "types": types})

	raw, err := fetch(awsSource)
	check(err)
	var spec struct {
		Version string `json:"ResourceSpecificationVersion"`
		Types   map[string]struct {
			Documentation string `json:"Documentation"`
		} `json:"ResourceTypes"`
	}
	check(json.Unmarshal(raw, &spec))
	if len(spec.Types) < 1000 {
		check(fmt.Errorf("only %d AWS types found; the source may have changed", len(spec.Types)))
	}
	docs := map[string]string{}
	for t, v := range spec.Types {
		docs[t] = v.Documentation
	}
	write(filepath.Join(dir, "aws.json"), map[string]any{"updated": today, "source": awsSource, "version": spec.Version, "types": docs})
	fmt.Printf("Azure: %d types, AWS: %d types (specification %s), %s\n", len(types), len(docs), spec.Version, today)
}

func fetch(url string) ([]byte, error) {
	c := &http.Client{Timeout: 2 * time.Minute}
	resp, err := c.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, 64<<20))
	if err != nil {
		return nil, err
	}
	// Still gzipped when the server sent it as a file, not an encoding.
	if len(data) > 2 && data[0] == 0x1f && data[1] == 0x8b {
		gz, err := gzip.NewReader(bytes.NewReader(data))
		if err != nil {
			return nil, err
		}
		return io.ReadAll(io.LimitReader(gz, 64<<20))
	}
	return data, nil
}

// write saves a map with sorted keys, one type per line, so a weekly
// refresh shows as a small, readable change.
func write(path string, v map[string]any) {
	var b strings.Builder
	b.WriteString("{\n")
	keys := make([]string, 0, len(v))
	for k := range v {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for i, k := range keys {
		kj, _ := json.Marshal(k)
		b.WriteString("  " + string(kj) + ": ")
		if m, ok := v[k].(map[string]string); ok {
			names := make([]string, 0, len(m))
			for n := range m {
				names = append(names, n)
			}
			sort.Strings(names)
			b.WriteString("{\n")
			for j, n := range names {
				nj, _ := json.Marshal(n)
				vj, _ := json.Marshal(m[n])
				b.WriteString("    " + string(nj) + ": " + string(vj))
				if j < len(names)-1 {
					b.WriteString(",")
				}
				b.WriteString("\n")
			}
			b.WriteString("  }")
		} else {
			vj, _ := json.Marshal(v[k])
			b.WriteString(string(vj))
		}
		if i < len(keys)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	check(os.WriteFile(path, []byte(b.String()), 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "update knowledge:", err)
		os.Exit(1)
	}
}
